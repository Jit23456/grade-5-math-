def read_question_form(f):
    qtype = f.get("type", "mcq")
    opts = split_lines(f.get("options"))
    if qtype == "fill":
        accept = split_lines(f.get("accept"))
        return dict(type=qtype, stem=f.get("stem", "").strip(), options=[],
                    answer=[], accept=accept,
                    display_answer=(f.get("display_answer") or (accept[0] if accept else "")),
                    unit=f.get("unit", "").strip(),
                    visual=f.get("visual", "").strip(),
                    explanation=f.get("explanation", "").strip(),
                    skill_tag=f.get("skill_tag", "").strip(),
                    difficulty=f.get("difficulty", "medium")), None
    picked = [int(x) for x in f.getlist("correct") if x.isdigit()]
    picked = sorted({i for i in picked if 0 <= i < len(opts)})
    if len(opts) < 2:
        return None, "Give at least two options."
    if not picked:
        return None, "Mark at least one option as correct."
    if qtype == "mcq" and len(picked) > 1:
        return None, "A multiple-choice question needs exactly one correct option. Use multi-select for more."
    keys = ["A", "B", "C", "D", "E", "F"]
    return dict(type=qtype, stem=f.get("stem", "").strip(), options=opts,
                answer=picked, accept=[],
                display_answer=" and ".join(keys[i] for i in picked),
                unit="", visual=f.get("visual", "").strip(),
                explanation=f.get("explanation", "").strip(),
                skill_tag=f.get("skill_tag", "").strip(),
                difficulty=f.get("difficulty", "medium")), None


