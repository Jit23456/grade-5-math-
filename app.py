def init_db():
    """Create the schema, seed the curriculum chapters, add the first teacher.

    A WSGI server such as gunicorn imports this module once per worker, so
    several processes may call this at the same moment on a cold start. The
    seeding runs inside BEGIN IMMEDIATE, which takes the write lock before the
    row count is read: the first worker seeds, and every other worker waits,
    then sees a non-empty table and does nothing. A unique index on the chapter
    number is the backstop if that ever fails.
    """
    os.makedirs(os.path.dirname(DB_PATH), exist_ok=True)
    con = sqlite3.connect(DB_PATH, timeout=30, isolation_level=None)
    con.row_factory = sqlite3.Row
    con.execute("PRAGMA busy_timeout = 30000")
    con.executescript(SCHEMA)
    try:
        con.execute("CREATE UNIQUE INDEX IF NOT EXISTS idx_ch_number_uniq"
                    " ON chapters(number)")
    except sqlite3.IntegrityError:
        pass  # an existing database already holds duplicate numbers; leave it alone

    # a database created before the 'visual' column existed needs it added by hand
    for tbl in ("chapters", "questions"):
        try:
            con.execute("ALTER TABLE %s ADD COLUMN visual TEXT NOT NULL DEFAULT ''" % tbl)
        except sqlite3.OperationalError:
            pass  # column already present
    # likewise for the phone column added with mobile sign-up
    try:
        con.execute("ALTER TABLE users ADD COLUMN phone TEXT NOT NULL DEFAULT ''")
    except sqlite3.OperationalError:
        pass
    con.execute("CREATE UNIQUE INDEX IF NOT EXISTS idx_users_phone"
                " ON users(phone) WHERE phone <> ''")
    # and the topic link and draft status added with topics
    for ddl in ("ALTER TABLE questions ADD COLUMN topic_id INTEGER"
                " REFERENCES topics(id) ON DELETE SET NULL",
                "ALTER TABLE questions ADD COLUMN status TEXT NOT NULL DEFAULT 'live'"):
        try:
            con.execute(ddl)
        except sqlite3.OperationalError:
            pass
    con.execute("CREATE INDEX IF NOT EXISTS idx_q_topic ON questions(topic_id)")

    con.execute("BEGIN IMMEDIATE")
    have = con.execute("SELECT COUNT(*) c FROM chapters").fetchone()["c"]
    if have == 0 and os.path.exists(SEED_PATH):
        with open(SEED_PATH, encoding="utf-8") as fh:
            seed = json.load(fh)   # explicit: Windows would otherwise decode it as cp1252
        for c in seed["chapters"]:
            cur = con.execute(
                "INSERT INTO chapters (number,title,strand,standard,elaborations,"
                "big_idea,lede,goals,vocab,body_md,summary,visual,source,author,published,"
                "created,updated) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,'curriculum','BC Curriculum',1,?,?)",
                (c["number"], c["title"], c["strand"], c["standard"],
                 json.dumps(c["elaborations"]), c["big_idea"], c["lede"],
                 json.dumps(c["goals"]), json.dumps(c["vocab"]), c["body_md"],
                 json.dumps(c["summary"]), c.get("visual", ""), now(), now()))
            cid = cur.lastrowid
            for q in c["questions"]:
                con.execute(
                    "INSERT INTO questions (chapter_id,position,type,stem,options,answer,"
                    "accept,display_answer,unit,visual,explanation,skill_tag,difficulty,source,"
                    "author,created) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,'curriculum','BC Curriculum',?)",
                    (cid, q["position"], q["type"], q["stem"], json.dumps(q["options"]),
                     json.dumps(q["answer"]), json.dumps(q["accept"]),
                     q["display_answer"], q["unit"], q.get("visual", ""), q["explanation"],
                     q["skill_tag"], q["difficulty"], now()))
        print("seeded %d chapters" % len(seed["chapters"]))
    split_lessons(con)

    users =con.execute("SELECT COUNT(*) c FROM users").fetchone()["c"]
    created_pw = None
    if users == 0:
        pw = os.environ.get("MATH5_ADMIN_PASSWORD")
        if not pw:
            pw = secrets.token_urlsafe(9)
            created_pw = pw
        con.execute("INSERT INTO users (username,pw_hash,display_name,role,created)"
                    " VALUES (?,?,?,?,?)",
                    ("teacher", generate_password_hash(pw), "Lead Teacher", "admin", now()))
    con.commit()
    con.close()
    if created_pw:
        print("\n" + "=" * 58)
        print("  First-run teacher account created")
        print("  username: teacher")
        print("  password: %s" % created_pw)
        print("  Change it from the teacher dashboard after signing in.")
        print("=" * 58 + "\n")


LESSON_HEAD = re.compile(r"^###\s+Lesson\b[ \t]*[\d.]*[ \t]*[-–—:]?[ \t]*(.*)$", re.M)


def split_lessons(con):
    """Chapters used to hold every lesson in one Markdown field, each starting
    with '### Lesson 1.1 - Title'. Turn each of those into its own topic, and
    keep whatever came before the first lesson as the chapter introduction.
    Runs only for a chapter that has no topics yet, and the heading is gone from
    the introduction afterwards, so it never splits the same chapter twice."""
    rows = con.execute(
        "SELECT * FROM chapters c WHERE body_md LIKE '%### Lesson%'"
        " AND NOT EXISTS (SELECT 1 FROM topics t WHERE t.chapter_id=c.id)").fetchall()
    for c in rows:
        body = c["body_md"]
        heads = list(LESSON_HEAD.finditer(body))
        if not heads:
            continue
        for i, m in enumerate(heads):
            end = heads[i + 1].start() if i + 1 < len(heads) else len(body)
            text = body[m.end():end].strip()
            title = m.group(1).strip() or "Lesson %d" % (i + 1)
            con.execute(
                "INSERT INTO topics (chapter_id,position,title,body_md,draft_md,status,"
                "source,author,created,updated) VALUES (?,?,?,?,?,'published',?,?,?,?)",
                (c["id"], i + 1, title, text, text, c["source"], c["author"], now(), now()))
        con.execute("UPDATE chapters SET body_md=? WHERE id=?",
                    (body[:heads[0].start()].strip(), c["id"]))


