@app.route("/signup", methods=["GET", "POST"])
def signup():
    """Step one: take the details, hold them aside, and text a code to the number.
    Nothing is written to `users` until the code comes back verified."""
    if current_user():
        return redirect(url_for("dashboard"))
    if request.method == "POST":
        f = request.form
        display = f.get("display_name", "").strip()
        phone = normalize_phone(f.get("phone"))
        pw = f.get("password", "")
        if not display:
            flash("Give your name, so your colleagues know who wrote what.", "error")
        elif not phone:
            flash("Enter a mobile number, including the country code, e.g. +16045550132.",
                  "error")
        elif len(pw) < 8:
            flash("Choose a password of at least 8 characters.", "error")
        elif db().execute("SELECT 1 FROM users WHERE phone=?", (phone,)).fetchone():
            flash("There is already an account for that mobile number. Sign in instead.",
                  "warn")
            return redirect(url_for("login"))
        else:
            row = db().execute("SELECT sends, last_sent FROM signup_otp WHERE phone=?",
                               (phone,)).fetchone()
            if row and row["sends"] >= OTP_MAX_SENDS:
                flash("That number has been sent too many codes. Try again later.", "error")
                return redirect(url_for("signup"))
            sent, err = start_otp(phone, display, generate_password_hash(pw))
            if err:
                flash("The code could not be sent: %s" % err, "error")
                return redirect(url_for("signup"))
            session["signup_phone"] = phone
            # when SMS is off the verify page already explains where the code went
            return redirect(url_for("signup_verify"))
        return redirect(url_for("signup"))
    return render_template("signup.html")


@app.route("/signup/verify", methods=["GET", "POST"])
def signup_verify():
    """Step two: check the code, then create the account and sign them in."""
    phone = session.get("signup_phone")
    if not phone:
        return redirect(url_for("signup"))
    row = db().execute("SELECT * FROM signup_otp WHERE phone=?", (phone,)).fetchone()
    if not row:
        flash("That code has expired. Please sign up again.", "warn")
        session.pop("signup_phone", None)
        return redirect(url_for("signup"))

    if request.method == "POST":
        if request.form.get("resend"):
            if row["sends"] >= OTP_MAX_SENDS:
                flash("That number has been sent too many codes. Try again later.", "error")
            elif row["last_sent"] >= (datetime.now(timezone.utc) -
                                      timedelta(seconds=OTP_RESEND_SECONDS)
                                      ).strftime("%Y-%m-%d %H:%M:%S"):
                flash("A code was just sent. Wait a minute before asking for another.", "warn")
            else:
                sent, err = start_otp(phone, row["display_name"], row["pw_hash"])
                flash(("The code could not be sent: %s" % err) if err else
                      ("A new code is on its way." if sent else
                       "A new code was written to the server log."),
                      "error" if err else "ok")
            return redirect(url_for("signup_verify"))

        if row["expires"] < now():
            db().execute("DELETE FROM signup_otp WHERE phone=?", (phone,))
            db().commit()
            flash("That code has expired. Please sign up again.", "warn")
            session.pop("signup_phone", None)
            return redirect(url_for("signup"))
        code = re.sub(r"\D", "", request.form.get("code", ""))
        if not check_password_hash(row["code_hash"], code):
            attempts = row["attempts"] + 1
            if attempts >= OTP_MAX_ATTEMPTS:
                # spent: throw the code away on this request rather than the next
                db().execute("DELETE FROM signup_otp WHERE phone=?", (phone,))
                db().commit()
                session.pop("signup_phone", None)
                flash("Too many wrong codes. Please sign up again.", "error")
                return redirect(url_for("signup"))
            db().execute("UPDATE signup_otp SET attempts=? WHERE phone=?", (attempts, phone))
            db().commit()
            left = OTP_MAX_ATTEMPTS - attempts
            flash("That code did not match. %d %s left."
                  % (left, "try" if left == 1 else "tries"), "error")
            return redirect(url_for("signup_verify"))

        # Verified. Build a username from the number, since it is already unique.
        username = "t" + phone.lstrip("+")[-10:]
        n = 0
        while db().execute("SELECT 1 FROM users WHERE username=?", (username,)).fetchone():
            n += 1
            username = "t%s-%d" % (phone.lstrip("+")[-10:], n)
        cur = db().execute(
            "INSERT INTO users (username,pw_hash,display_name,phone,role,created)"
            " VALUES (?,?,?,?,'teacher',?)",
            (username, row["pw_hash"], row["display_name"], phone, now()))
        db().execute("DELETE FROM signup_otp WHERE phone=?", (phone,))
        db().commit()
        session.clear()
        session["uid"] = cur.lastrowid
        flash("Welcome, %s. Your mobile number is verified and you are signed in."
              % row["display_name"], "ok")
        return redirect(url_for("dashboard"))

    return render_template("signup_verify.html", phone=phone, sms_ready=SMS_READY)


