def bar_segments(pairs, width=200, gap=2):
    """Turn [(label,color,count), ...] into rounded-rect segments for an
    inline SVG stacked bar: a thin horizontal chart with a 2px gap between
    fills, sized for a `width`-unit viewBox. Zero-count entries are dropped
    so the legend only lists what is actually present."""
    items = [(l, c, n) for l, c, n in pairs if n]
    total = sum(n for _, _, n in items)
    segments = []
    if not total:
        return segments, 0
    avail = width - gap * (len(items) - 1) if len(items) > 1 else width
    x = 0.0
    for label, color, count in items:
        w = count / total * avail
        segments.append(dict(label=label, color=color, count=count,
                             pct=round(count / total * 100), x=round(x, 2), width=round(w, 2)))
        x += w + gap
    return segments, total


