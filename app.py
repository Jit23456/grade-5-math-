@app.route("/login", methods=["GET", "POST"])
def login():
    if request.method == "POST":
        # Someone who signed up by mobile knows their number, not the username
        # that was generated for them, so either one is accepted here.
        ident = request.form.get("username", "").strip().lower()
        phone = normalize_phone(ident)
        u = db().execute(
            "SELECT * FROM users WHERE username=? OR (phone <> '' AND phone=?)",
            (ident, phone or "\x00")).fetchone()
        if u and check_password_hash(u["pw_hash"], request.form.get("password", "")):
            session.clear()
            session["uid"] = u["id"]
            nxt = request.form.get("next") or url_for("dashboard")
            if not nxt.startswith("/"):
                nxt = url_for("dashboard")
            return redirect(nxt)
        flash("Those details did not match an account.", "error")
    return render_template("login.html", next=request.args.get("next", ""))


