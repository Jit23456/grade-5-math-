PHONE_DIGITS = re.compile(r"[^0-9+]")


def normalize_phone(raw):
    """Reduce what someone typed to a comparable form: digits with an optional
    leading +. Spaces, dashes and brackets are all dropped, so '+1 (604) 555-0132'
    and '+16045550132' are the same number. Returns '' if it cannot be one."""
    s = PHONE_DIGITS.sub("", (raw or "").strip())
    if s.startswith("+"):
        s = "+" + s[1:].replace("+", "")
    else:
        s = s.replace("+", "")
    digits = s.lstrip("+")
    if not digits.isdigit() or not (7 <= len(digits) <= 15):
        return ""
    return s


def send_sms(to, body):
    """Text `body` to `to`. Returns (sent, error). With no provider configured
    the code goes to the server log instead, and sent is False with no error."""
    if not SMS_READY:
        print("\n[sign-up] SMS is not configured. Code for %s: %s\n" % (to, body))
        return False, None
    url = "https://api.twilio.com/2010-04-01/Accounts/%s/Messages.json" % SMS_SID
    data = urllib.parse.urlencode({"From": SMS_FROM, "To": to, "Body": body}).encode()
    auth = base64.b64encode(("%s:%s" % (SMS_SID, SMS_TOKEN)).encode()).decode()
    req = urllib.request.Request(url, data=data, method="POST", headers={
        "Authorization": "Basic %s" % auth,
        "Content-Type": "application/x-www-form-urlencoded",
    })
    try:
        with urllib.request.urlopen(req, timeout=20) as r:
            r.read()
        return True, None
    except urllib.error.HTTPError as e:
        try:
            msg = json.loads(e.read().decode()).get("message", "HTTP %s" % e.code)
        except Exception:
            msg = "HTTP %s from the SMS provider." % e.code
        return False, msg
    except Exception as e:
        return False, "Could not reach the SMS provider: %s" % e


def start_otp(phone, display_name, pw_hash):
    """Create or replace the pending sign-up for this number and text a code."""
    code = "%06d" % secrets.randbelow(1000000)
    expires = (datetime.now(timezone.utc) + timedelta(minutes=OTP_MINUTES)
               ).strftime("%Y-%m-%d %H:%M:%S")
    db().execute(
        "INSERT INTO signup_otp (phone,code_hash,display_name,pw_hash,attempts,sends,"
        "last_sent,expires,created) VALUES (?,?,?,?,0,1,?,?,?) "
        "ON CONFLICT(phone) DO UPDATE SET code_hash=excluded.code_hash,"
        "display_name=excluded.display_name, pw_hash=excluded.pw_hash, attempts=0,"
        "sends=signup_otp.sends+1, last_sent=excluded.last_sent, expires=excluded.expires",
        (phone, generate_password_hash(code), display_name, pw_hash, now(), expires, now()))
    db().commit()
    return send_sms(phone, "Your Mathematics 5 verification code is %s. "
                           "It expires in %d minutes." % (code, OTP_MINUTES))


def admin_required(fn):
    """Managing accounts is the one thing a plain teacher cannot do: every
    signed-in teacher may write content, but only an admin lets someone new in."""
    @wraps(fn)
    def inner(*a, **kw):
        u = current_user()
        if not u:
            flash("Please sign in to reach the teacher area.", "warn")
            return redirect(url_for("login", next=request.path))
        if u["role"] != "admin":
            flash("Only an admin can manage teacher accounts.", "error")
            return redirect(url_for("dashboard"))
        return fn(*a, **kw)
    return inner


