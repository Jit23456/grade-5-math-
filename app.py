def chapter_row(number):
    r = db().execute("SELECT * FROM chapters WHERE number=?", (number,)).fetchone()
    if not r:
        abort(404)
    return r


def questions_for(cid):
    rows = db().execute(
        "SELECT * FROM questions WHERE chapter_id=? ORDER BY position, id", (cid,)).fetchall()
    out = []
    for r in rows:
        d = dict(r)
        d["options"] = jl(r["options"])
        d["answer"] = jl(r["answer"])
        d["accept"] = jl(r["accept"])
        out.append(d)
    return out


def chapter_dict(r):
    d = dict(r)
    d["elaborations"] = jl(r["elaborations"])
    d["goals"] = jl(r["goals"])
    d["vocab"] = jl(r["vocab"])
    d["summary"] = jl(r["summary"])
    d["body_html"] = render_md(r["body_md"])
    d["lesson_count"] = r["body_md"].count("### Lesson")
    return d


